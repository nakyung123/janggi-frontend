// 글 셋이 독자가 다르다. 같은 변경을 세 번 적는 것이 아니라, 읽는 사람이 다르다.
//
//   커밋 메시지   - 나중의 나.         무엇을 왜 고쳤나
//   DECISIONS.md - 이 코드를 보는 사람. 왜 그렇게 정했나
//   여기          - 장기 두는 사람.     무엇이 달라졌나
//
// 그래서 여기만 '~해요' 로 적는다. 기능 이름(`outcomeOf`, `clipPath`)을 쓰지 않고
// 화면에서 무엇이 달라지는지를 쓴다. 뺀 것도 적는다 - 더한 것만 적으면 홍보가
// 되고, 뺀 것도 적어야 기록이 된다.
//
// 앱과 업데이트 페이지가 이 한 파일을 같이 읽는다. 버전을 두 군데 적으면
// 화면에 뜨는 버전과 제보에 붙는 버전이 어긋나고, 어긋난 줄도 모른다.

