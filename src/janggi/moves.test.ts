import { describe, expect, it } from "vitest";
import type { Board, Square } from "./board";
import { pieceMoves } from "./moves";

/*
 * 행마 테스트. 기대하는 자리는 손으로 따져 적었다.
 *
 * "엔진" 이라고 적은 국면은 Fairy-Stockfish(대국에서 쓰는 엔진)에 같은 국면을 넣어 합법수를
 * 찍어 본 것과 같다. 대국 화면은 엔진의 합법수로 기물을 옮기고 배우기 화면은 이 계산으로
 * 옮기므로, 둘이 다르면 배우기에서 익힌 움직임이 대국에서 안 된다.
 */

/** 순서는 보지 않는다. */
const 갈곳 = (board: Board, from: Square) => [...pieceMoves(board, from)].sort();
const 자리 = (...squares: Square[]) => [...squares].sort();

describe("궁·사 - 궁성 안에서 선을 따라 한 칸", () => {
  it("가운데에서는 여덟 방향 (엔진: 사 e2)", () => {
    expect(갈곳({ e2: "A" }, "e2")).toEqual(자리("d1", "e1", "f1", "d2", "f2", "d3", "e3", "f3"));
    expect(갈곳({ e2: "K" }, "e2")).toEqual(자리("d1", "e1", "f1", "d2", "f2", "d3", "e3", "f3"));
  });

  it("귀에서는 가운데로 가는 대각선이 있다 (엔진: 궁 d1)", () => {
    expect(갈곳({ d1: "K" }, "d1")).toEqual(자리("d2", "e1", "e2"));
  });

  it("변 가운데에는 대각선 선이 없다 (엔진: 궁 e1)", () => {
    expect(갈곳({ e1: "K" }, "e1")).toEqual(자리("d1", "e2", "f1"));
  });

  it("궁성 밖으로 나가지 못한다 - 한의 궁성 귀", () => {
    expect(갈곳({ d8: "k" }, "d8")).toEqual(자리("d9", "e8", "e9"));
  });

  it("내 기물 자리로는 못 가고, 상대 기물 자리는 잡는다", () => {
    expect(갈곳({ e2: "K", d1: "A", f3: "p" }, "e2")).toEqual(
      자리("e1", "f1", "d2", "f2", "d3", "e3", "f3")
    );
  });
});

describe("차 - 곧게 몇 칸이든", () => {
  it("빈 판에서는 가로줄과 세로줄 전부", () => {
    expect(갈곳({ e5: "R" }, "e5")).toEqual(
      자리(
        "a5", "b5", "c5", "d5", "f5", "g5", "h5", "i5",
        "e1", "e2", "e3", "e4", "e6", "e7", "e8", "e9", "e10"
      )
    );
  });

  it("내 기물 앞에서 멈추고, 상대 기물은 잡고 멈춘다", () => {
    expect(갈곳({ e5: "R", e7: "P", c5: "p" }, "e5")).toEqual(
      자리("e6", "d5", "c5", "f5", "g5", "h5", "i5", "e4", "e3", "e2", "e1")
    );
  });

  it("궁성 대각선을 탄다 (엔진: d8 → e9, f10)", () => {
    expect(갈곳({ d8: "R" }, "d8")).toEqual(
      자리(
        "d1", "d2", "d3", "d4", "d5", "d6", "d7", "d9", "d10",
        "a8", "b8", "c8", "e8", "f8", "g8", "h8", "i8",
        "e9", "f10"
      )
    );
  });

  it("궁성 대각선은 궁성이 끝나는 귀에서 멈춘다", () => {
    const moves = 갈곳({ f10: "R" }, "f10");
    expect(moves).toEqual(expect.arrayContaining(["e9", "d8"]));
    expect(moves).not.toContain("c7");
  });

  it("궁성 대각선에서도 막히면 멈추고 상대 기물은 잡는다", () => {
    expect(갈곳({ d8: "R", e9: "N" }, "d8")).not.toContain("e9");
    expect(갈곳({ d8: "R", e9: "N" }, "d8")).not.toContain("f10");
    expect(갈곳({ d8: "R", e9: "n" }, "d8")).toContain("e9");
    expect(갈곳({ d8: "R", e9: "n" }, "d8")).not.toContain("f10");
  });

  it("궁성 밖의 대각선으로는 가지 않는다", () => {
    expect(갈곳({ c7: "R" }, "c7")).not.toContain("d8");
  });
});

describe("포 - 기물 하나를 넘어서", () => {
  it("넘을 기물이 없으면 갈 곳이 없다", () => {
    expect(갈곳({ e5: "C" }, "e5")).toEqual([]);
  });

  it("기물 하나를 넘어 그 뒤로 간다 - 넘는 기물은 내 편이든 상대 편이든", () => {
    expect(갈곳({ b3: "C", b5: "P" }, "b3")).toEqual(자리("b6", "b7", "b8", "b9", "b10"));
    expect(갈곳({ b3: "C", b5: "p" }, "b3")).toEqual(자리("b6", "b7", "b8", "b9", "b10"));
  });

  it("넘은 뒤 처음 만난 상대 기물은 잡고, 내 기물이면 그 앞에서 멈춘다", () => {
    expect(갈곳({ b3: "C", b5: "P", b8: "r" }, "b3")).toEqual(자리("b6", "b7", "b8"));
    expect(갈곳({ b3: "C", b5: "P", b8: "R" }, "b3")).toEqual(자리("b6", "b7"));
  });

  it("포는 포를 넘지 못한다 - 같은 자리가 병이면 넘는다 (엔진)", () => {
    expect(갈곳({ b3: "C", b5: "c" }, "b3")).toEqual([]);
    expect(갈곳({ b3: "C", b5: "C" }, "b3")).toEqual([]);
    expect(갈곳({ b3: "C", b5: "p" }, "b3")).not.toEqual([]);
  });

  it("포는 포를 잡지 못한다 (엔진)", () => {
    expect(갈곳({ b3: "C", b5: "P", b8: "c" }, "b3")).toEqual(자리("b6", "b7"));
  });

  it("궁성에서는 가운데 기물을 넘어 대각선으로 간다 (엔진: d1 → f3, e2 에 사)", () => {
    expect(갈곳({ d1: "C", e2: "A" }, "d1")).toEqual(["f3"]);
    expect(갈곳({ d1: "C", e2: "A", f3: "r" }, "d1")).toEqual(["f3"]);
    expect(갈곳({ d1: "C", e2: "A", f3: "R" }, "d1")).toEqual([]);
  });

  it("궁성 대각선에서도 포는 넘지도 잡지도 못한다", () => {
    expect(갈곳({ d1: "C", e2: "c" }, "d1")).toEqual([]);
    expect(갈곳({ d1: "C", e2: "A", f3: "c" }, "d1")).toEqual([]);
  });
});

describe("마 - 한 칸 곧게, 한 칸 대각선", () => {
  it("빈 판에서는 여덟 자리", () => {
    expect(갈곳({ e5: "N" }, "e5")).toEqual(
      자리("c4", "c6", "d3", "d7", "f3", "f7", "g4", "g6")
    );
  });

  it("첫 칸이 막히면 그쪽 두 자리에 못 간다 - 멱 (엔진: b1, b2 를 막으면 a3·c3 이 사라짐)", () => {
    expect(갈곳({ b1: "N" }, "b1")).toEqual(자리("a3", "c3", "d2"));
    expect(갈곳({ b1: "N", b2: "P" }, "b1")).toEqual(["d2"]);
    expect(갈곳({ b1: "N", b2: "p" }, "b1")).toEqual(["d2"]);
  });

  it("내 기물 자리로는 못 가고, 상대 기물 자리는 잡는다", () => {
    expect(갈곳({ b1: "N", a3: "P", c3: "p" }, "b1")).toEqual(자리("c3", "d2"));
  });

  it("궁성 대각선을 쓰지 않는다", () => {
    expect(갈곳({ e2: "N" }, "e2")).toEqual(자리("c1", "c3", "d4", "f4", "g1", "g3"));
  });
});

describe("상 - 한 칸 곧게, 두 칸 대각선", () => {
  it("빈 판에서는 여덟 자리", () => {
    expect(갈곳({ e5: "B" }, "e5")).toEqual(
      자리("b3", "b7", "c2", "c8", "g2", "g8", "h3", "h7")
    );
  });

  it("곧게 가는 첫 칸이 막히면 그쪽 두 갈래가 다 막힌다 (엔진)", () => {
    expect(갈곳({ e5: "B", e6: "P" }, "e5")).toEqual(자리("b3", "b7", "c2", "g2", "h3", "h7"));
  });

  it("대각선 첫 칸이 막히면 그 갈래만 막힌다 (엔진)", () => {
    expect(갈곳({ e5: "B", f7: "P" }, "e5")).toEqual(
      자리("b3", "b7", "c2", "c8", "g2", "h3", "h7")
    );
  });

  it("도착 자리 바로 앞(대각선 둘째 칸)은 막는 자리가 아니라 갈 곳이다", () => {
    expect(갈곳({ e5: "B", g8: "p" }, "e5")).toContain("g8");
    expect(갈곳({ e5: "B", g8: "P" }, "e5")).not.toContain("g8");
  });
});

describe("졸·병 - 앞이나 옆으로 한 칸", () => {
  it("초의 졸은 위가 앞이다. 뒤로는 못 간다", () => {
    expect(갈곳({ e4: "P" }, "e4")).toEqual(자리("d4", "e5", "f4"));
  });

  it("한의 병은 아래가 앞이다", () => {
    expect(갈곳({ e7: "p" }, "e7")).toEqual(자리("d7", "e6", "f7"));
  });

  it("궁성 밖에서는 대각선이 없다 (엔진: c5)", () => {
    expect(갈곳({ c5: "P" }, "c5")).toEqual(자리("b5", "c6", "d5"));
  });

  it("상대 궁성 가운데에서는 대각선 앞으로도 간다. 뒤로는 없다 (엔진: e9)", () => {
    expect(갈곳({ e9: "P" }, "e9")).toEqual(자리("d9", "d10", "e10", "f9", "f10"));
  });

  it("상대 궁성 귀에서는 가운데로 가는 대각선만 (엔진: d8 → e9)", () => {
    expect(갈곳({ d8: "P" }, "d8")).toEqual(자리("c8", "d9", "e8", "e9"));
  });

  it("한의 병도 초의 궁성에서 대각선 앞(아래)으로 간다", () => {
    expect(갈곳({ d3: "p" }, "d3")).toEqual(자리("c3", "d2", "e2", "e3"));
  });

  it("끝줄에서는 옆으로만", () => {
    expect(갈곳({ a10: "P" }, "a10")).toEqual(["b10"]);
  });
});

describe("기물이 없는 자리", () => {
  it("갈 곳이 없다", () => {
    expect(pieceMoves({ e2: "K" }, "e5")).toEqual([]);
  });
});
